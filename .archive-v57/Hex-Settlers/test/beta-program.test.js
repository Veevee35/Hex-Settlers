'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { BetaProgram, cleanReferral } = require('../server/beta-program');

test('beta visitor and account attribution count distinct users and retain campaign source', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hex-beta-test-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  let now = Date.UTC(2026,10,10,17);
  const store = new BetaProgram(path.join(dir,'beta_program.json'), { now:()=>now });
  const a = 'a'.repeat(32), b = 'b'.repeat(32);
  store.visit(a,'discord-catan');store.visit(a,'reddit');store.visit(b,'r-playmygame');
  store.account('user-1',a,'direct');store.account('user-1',b,'direct');
  store.account('user-2',b,'direct');
  store.stage('user-1','tutorialStarts');store.stage('user-1','tutorialStarts');
  store.stage('user-1','tutorialFinishes');store.stage('user-1','gamesStarted');
  store.stage('user-1','gamesStarted');store.count('gamesStarted');
  store.gameFinished('room-1',['user-1','user-2']);
  store.gameFinished('room-1',['user-1']);
  await store.save();
  const report=store.report('week');
  assert.equal(report.uniqueVisitors,2);
  assert.equal(report.activeAccounts,2);
  assert.equal(report.totals.visits,2);
  assert.equal(report.totals.accounts,2);
  assert.equal(report.totals.tutorialStarts,1);
  assert.equal(report.totals.gamesStarted,1);
  assert.equal(report.totals.gamesFinished,1);
  assert.equal(report.repeatPlayers,1);
  assert.equal(report.funnel.gamesFinished,2);
  assert.equal(report.referrals.find(x=>x.source==='discord-catan').accounts,1);
  assert.equal(report.referrals.find(x=>x.source==='r-playmygame').accounts,1);
  assert.ok(!JSON.stringify(store.state).includes('user-1'));
  assert.ok(!JSON.stringify(store.state).includes(a));
  const reload=new BetaProgram(path.join(dir,'beta_program.json'), { now:()=>now });
  assert.equal(reload.report().funnel.gamesFinished,2);
  now += 86400000;
  reload.visit(a,'new-promo');
  assert.equal(reload.report('week').totals.visits,3);
  assert.equal(reload.report('week').referrals.find(x=>x.source==='discord-catan').visits,1);
});

test('feedback is validated, bounded, and administrative state changes are durable',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'hex-beta-feedback-'));t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const now=Date.UTC(2026,10,10,18);
  const store=new BetaProgram(path.join(dir,'beta_program.json'), {now:()=>now});
  assert.throws(()=>store.feedback({category:'bug',description:'short'}),/12 characters/);
  const id=store.feedback({userId:'user-1',category:'bug',description:'The resource dock is missing after reconnect',steps:'Open the lobby\u0000 and reconnect',roomCode:'ABCD',build:'V1.0.68',device:'mobile'});
  store.setFeedbackStatus(id,'triaged');
  const item=store.report().feedback[0];
  assert.equal(item.status,'triaged');assert.equal(item.roomCode,'ABCD');
  assert.ok(!item.steps.includes('\u0000'));assert.ok(!JSON.stringify(item).includes('user-1'));
  assert.throws(()=>store.setFeedbackStatus(id,'admin'),/Invalid/);
  const session=store.setSession({title:'Tuesday group test',notes:'Test ranked matchmaking',startAt:now+3600000,endAt:now+7200000});
  assert.equal(store.upcoming().length,1);
  await store.save();
  const reload=new BetaProgram(path.join(dir,'beta_program.json'),{now:()=>now});
  assert.equal(reload.report().feedback[0].status,'triaged');
  assert.equal(reload.upcoming()[0].title,'Tuesday group test');
  assert.equal(reload.removeSession(session.id),true);
  await reload.flush();
  const again=new BetaProgram(path.join(dir,'beta_program.json'),{now:()=>now});
  assert.equal(again.upcoming().length,0);
});

